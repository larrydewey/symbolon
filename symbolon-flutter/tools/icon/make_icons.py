#!/usr/bin/env python3
"""The Symbolon mark, and every Android icon and splash resource made from it.

A symbolon was a token broken in two, each party keeping one half. The mark
is that token: a round coin with a rim, broken along a zigzag seam, its two
halves slightly apart. The geometry here is the one source of truth; the
same shape is drawn in the app by lib/brand.dart.

    tools/icon/make_icons.py            # from symbolon-flutter/

writes the adaptive launcher icon (with a monochrome layer for themed
icons), the splash screen, and the legacy PNG icons for Android 7. The PNGs
are rendered with the pre-installed Chromium through Playwright (node); the
vector resources need nothing.
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', '..', 'android', 'app', 'src', 'main', 'res')

# Brand colours, as in lib/brand.dart.
INDIGO = '#283593'       # the background
INDIGO_NIGHT = '#141A4D'  # the splash in dark mode
PAPER = '#FFFFFF'        # the left half
GOLD = '#FFC857'         # the right half

# The mark, in a 214 x 200 box (x 20..194, y 17..183).
SEAM = [(100, 180), (92, 160), (108, 140), (90, 120), (110, 100), (92, 80), (108, 60), (94, 40), (100, 20)]
GAP = 14   # how far apart the halves are
DY = 3     # the left half sits this much lower, the right this much higher
CX, CY, W = 107, 100, 174


def _f(v):
    return f'{v:g}'


def left_half():
    """The left half, with its rim cut out (even-odd)."""
    y = lambda v: _f(v + DY)
    seam = ' '.join(f'L{x} {y(v)}' for x, v in SEAM[1:-1])
    body = f'M100 {y(20)} A80 80 0 0 0 100 {y(180)} {seam} Z'
    rim = f'M90 {y(33.75)} A67 67 0 0 0 90 {y(166.25)} L90 {y(160.18)} A61 61 0 0 1 90 {y(39.82)} Z'
    return f'{body} {rim}'


def right_half():
    y = lambda v: _f(v - DY)
    seam = ' '.join(f'L{x + GAP} {y(v)}' for x, v in SEAM[1:-1])
    body = f'M{100 + GAP} {y(20)} A80 80 0 0 1 {100 + GAP} {y(180)} {seam} Z'
    rim = f'M124 {y(33.75)} A67 67 0 0 1 124 {y(166.25)} L124 {y(160.18)} A61 61 0 0 0 124 {y(39.82)} Z'
    return f'{body} {rim}'


def placement(width):
    """The scale and offset that centre the mark, [width] wide, in a 108 canvas."""
    s = width / W
    return s, 54 - CX * s, 54 - CY * s


def vector(width, left, right, comment):
    s, tx, ty = placement(width)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/icon/make_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{tx:.4f}" android:translateY="{ty:.4f}" android:scaleX="{s:.5f}" android:scaleY="{s:.5f}">
        <path android:fillType="evenOdd" android:fillColor="{left}" android:pathData="{left_half()}"/>
        <path android:fillType="evenOdd" android:fillColor="{right}" android:pathData="{right_half()}"/>
    </group>
</vector>
'''


def svg(width, background, radius):
    s, tx, ty = placement(width)
    bg = '' if background is None else f'<rect width="108" height="108" rx="{radius}" fill="{background}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{bg}'
            f'<g transform="translate({tx:.4f} {ty:.4f}) scale({s:.5f})">'
            f'<path fill-rule="evenodd" fill="{PAPER}" d="{left_half()}"/>'
            f'<path fill-rule="evenodd" fill="{GOLD}" d="{right_half()}"/></g></svg>')


def write(path, text):
    full = os.path.join(RES, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(full, os.path.join(HERE, '..', '..')))


def main():
    # The adaptive icon: the mark fits the 66 dp safe zone of the 108 dp layer.
    write('drawable/ic_launcher_foreground.xml', vector(58, PAPER, GOLD, 'The launcher icon\'s foreground: the Symbolon mark.'))
    write('drawable/ic_launcher_monochrome.xml', vector(58, '#FF000000', '#FF000000', 'The mark in one colour, for themed icons (Android 13+).'))
    write('values/ic_launcher_colors.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/make_icons.py. -->
<resources>
    <color name="ic_launcher_background">{INDIGO}</color>
    <color name="splash_background">{INDIGO}</color>
</resources>
''')
    write('values-night/ic_launcher_colors.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/make_icons.py. -->
<resources>
    <color name="splash_background">{INDIGO_NIGHT}</color>
</resources>
''')
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/make_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
'''
    write('mipmap-anydpi-v26/ic_launcher.xml', adaptive)
    write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive)
    # The splash before Android 12 (Android 12+ draws it from the theme, values-v31).
    splash = '''<?xml version="1.0" encoding="utf-8"?>
<!-- The splash screen before Android 12: the mark on the brand colour.
     Generated by tools/icon/make_icons.py. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background"/>
    <item android:gravity="center" android:width="160dp" android:height="160dp" android:drawable="@drawable/ic_launcher_foreground"/>
</layer-list>
'''
    write('drawable/launch_background.xml', splash)
    write('drawable-v21/launch_background.xml', splash)

    # Legacy icons (Android 7, before adaptive icons), and the master SVGs.
    with open(os.path.join(HERE, 'symbolon-icon.svg'), 'w') as f:
        f.write(svg(66, INDIGO, 24) + '\n')
    with open(os.path.join(HERE, 'symbolon-mark.svg'), 'w') as f:
        f.write(svg(108, None, 0) + '\n')
    sizes = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}
    jobs = []
    for d, px in sizes.items():
        jobs.append((svg(66, INDIGO, 24), px, os.path.join(RES, f'mipmap-{d}', 'ic_launcher.png')))
        jobs.append((svg(66, INDIGO, 54), px, os.path.join(RES, f'mipmap-{d}', 'ic_launcher_round.png')))
    render(jobs)


def render(jobs):
    script = '''
const { chromium } = require('playwright');
const jobs = JSON.parse(require('fs').readFileSync(process.argv[2], 'utf8'));
(async () => {
  const b = await chromium.launch();
  for (const [svg, px, out] of jobs) {
    const p = await b.newPage({ viewport: { width: px, height: px } });
    await p.setContent(`<html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg width="${px}" height="${px}" `)}</body></html>`);
    await p.screenshot({ path: out, omitBackground: true });
    await p.close();
    console.log('wrote', out);
  }
  await b.close();
})();
'''
    import json
    with tempfile.TemporaryDirectory() as d:
        js, data = os.path.join(d, 'render.js'), os.path.join(d, 'jobs.json')
        with open(js, 'w') as f:
            f.write(script)
        with open(data, 'w') as f:
            json.dump(jobs, f)
        env = dict(os.environ)
        root = subprocess.run(['npm', 'root', '-g'], capture_output=True, text=True).stdout.strip()
        env['NODE_PATH'] = os.pathsep.join(p for p in [env.get('NODE_PATH', ''), root] if p)
        r = subprocess.run(['node', js, data], env=env)
        if r.returncode != 0:
            sys.exit('rendering the PNG icons failed: they need node and Playwright with Chromium')


if __name__ == '__main__':
    main()
