#!/usr/bin/env python3
"""Generates src/threshold/reshare_test.resid (from the keygen harness): a 2-of-3 key generation over the
wire with Paillier safe primes from the Resid CGGMP oracle's keys6.json, then
a blind-tweak signing session with the resulting configurations. The final
signature is printed by nothing; it is checked in the test under the P the
test derives, and the derivation itself is checked against Python in
threshold_ref_test.

    python3 tests/gen_keygen_ref.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
keys = json.load(open(os.path.expanduser('~/git/larry/resid/tests/crypto/cggmp_oracle/keys6.json')))
nat = lambda h: f'nat("{h}")'
primes = ',\n        '.join(f'[{nat(k["P"])}, {nat(k["Q"])}]' for k in keys[:6])

out = f'''// Key generation (src/threshold/keygen.resid) for parties 1, 2, 3 at
// threshold 2 (degree 1), every message through the wire, then a signing
// session with the configurations it made. Generated by
// tests/gen_keygen_ref.py; do not edit by hand.

import "../types.resid";
import "keygen.resid";
import "reshare.resid";
import "threshold.resid";
import "../net/wire.resid";
import "cose.resid";
import "crypto.resid";
import "ecdsa.resid";

List(UInt(64)) nat(Str h) {{ return bn_from_be(cose_hex_decode(h)); }}

List(List(List(UInt(64)))) primes() {{
    return [
        {primes}];
}}

type KgP = {{ Int id; KgState st; }};

Bool for_me(ThMsg m, Int me) {{
    return match m {{ ThCg(c) => c.from != me && (c.to == 0 || c.to == me), _ => false }};
}}

List(ThMsg) inbox(List(ThMsg) all, Int me, Int i, ListBuf(ThMsg) acc) {{
    if (i >= all.len()) {{ return acc.finish(); }}
    Option(ThMsg) d = msg_decode(msg_encode(all[i]));
    ListBuf(ThMsg) a = match d {{ Some(m) => if (for_me(m, me)) {{ acc.push(m) }} else {{ acc }}, None => acc }};
    return inbox(all, me, i + 1, a);
}}

type Round = {{ List(KgP) ps; List(ThMsg) out; Str fail; }};

Round failed(ListBuf(KgP) acc, CgFail e) {{ _ = acc.finish(); return Round {{ .ps = [], .out = [], .fail = e.why }}; }}

Round step_all(List(KgP) ps, List(ThMsg) in, Int i, ListBuf(KgP) acc, List(ThMsg) out) {{
    if (i >= ps.len()) {{ return Round {{ .ps = acc.finish(), .out = out, .fail = "" }}; }}
    return match kg_step(ps[i].st, inbox(in, ps[i].id, 0, ListBuf())) {{
        Err(e) => failed(acc, e),
        Ok(s) => step_all(ps, in, i + 1, acc.push(KgP {{ .id = ps[i].id, .st = s.state }}), out.concat(s.out))
    }};
}}

Round run(List(KgP) ps, List(ThMsg) in, Int rounds) {{
    if (rounds == 0) {{ return Round {{ .ps = ps, .out = in, .fail = "" }}; }}
    Round r = step_all(ps, in, 0, ListBuf(), []);
    if (str_len(r.fail) > 0) {{ return r; }}
    return run(r.ps, r.out, rounds - 1);
}}

Round begin(List(Int) ids, Int i, ListBuf(KgP) acc, List(ThMsg) out) {{
    if (i >= ids.len()) {{ return Round {{ .ps = acc.finish(), .out = out, .fail = "" }}; }}
    KgCtx c = kg_ctx(ids[i], ids, 1, [], bytes_of("symbolon keygen test"), sha256_bytes([ids[i], 9]), primes()[ids[i] - 1]);
    return match kg_begin(c) {{
        Err(e) => failed(acc, e),
        Ok(s) => begin(ids, i + 1, acc.push(KgP {{ .id = ids[i], .st = s.state }}), out.concat(s.out))
    }};
}}

CgConfig none_cfg() {{ return CgConfig {{ .id = 0, .threshold = 0, .ecdsa = [], .elgamal = [], .p = [], .q = [], .rid = [], .chain_key = [], .public = [] }}; }}

List(CgConfig) configs(Round r, Int i, List(CgConfig) acc) {{
    if (i >= r.ps.len()) {{ return acc; }}
    return configs(r, i + 1, acc.concat([kg_result(r.ps[i].st) else {{ none_cfg() }}]));
}}

List(CgConfig) keygen() {{
    Round r0 = begin([1, 2, 3], 0, ListBuf(), []);
    if (str_len(r0.fail) > 0) {{ return []; }}
    Round r = run(r0.ps, r0.out, 4);
    if (str_len(r.fail) > 0) {{ return []; }}
    return configs(r, 0, []);
}}

// x from a pair of shares by Lagrange at zero, times G.
List(Int) from_pair(List(CgConfig) cs, Int a, Int b) {{
    List(Int) ids = [a, b];
    List(UInt(64)) x = sc_nat_add(sc_nat_mul(cg_lagrange(ids, a), cs[a - 1].ecdsa), sc_nat_mul(cg_lagrange(ids, b), cs[b - 1].ecdsa));
    return sec1_uncompressed(cv_mul_base(x));
}}

Party party_of(Int n, UInt(8) kind) {{
    return Party {{ .id = [n, n, n, n], .kind = kind, .auth_key = [], .hpke_key = [], .label = "p", .attestation = NoAttestation }};
}}

type SgP = {{ CgCtx ctx; ThState st; }};

Bool sfor(ThMsg m, Int me) {{
    return match m {{ ThCg(c) => c.from != me && (c.to == 0 || c.to == me), ThTw(t) => t.to == me, ThAbortReq(f) => f != me, ThRs(r) => r.from != me && (r.to == 0 || r.to == me) }};
}}

List(ThMsg) sinbox(List(ThMsg) all, Int me, Int i, ListBuf(ThMsg) acc) {{
    if (i >= all.len()) {{ return acc.finish(); }}
    Option(ThMsg) d = msg_decode(msg_encode(all[i]));
    ListBuf(ThMsg) a = match d {{ Some(m) => if (sfor(m, me)) {{ acc.push(m) }} else {{ acc }}, None => acc }};
    return sinbox(all, me, i + 1, a);
}}

type SR = {{ List(SgP) ss; List(ThMsg) out; Str fail; }};

SR sfailed(ListBuf(SgP) acc, CgFail e) {{ _ = acc.finish(); return SR {{ .ss = [], .out = [], .fail = e.why }}; }}

SR sstep(List(SgP) ss, List(ThMsg) in, Int i, ListBuf(SgP) acc, List(ThMsg) out) {{
    if (i >= ss.len()) {{ return SR {{ .ss = acc.finish(), .out = out, .fail = "" }}; }}
    return match th_step(ss[i].st, sinbox(in, ss[i].ctx.self, 0, ListBuf())) {{
        Err(e) => sfailed(acc, e),
        Ok(s) => sstep(ss, in, i + 1, acc.push(SgP {{ .ctx = ss[i].ctx, .st = s.state }}), out.concat(s.out))
    }};
}}

SR srun(List(SgP) ss, List(ThMsg) in, Int rounds) {{
    if (rounds == 0) {{ return SR {{ .ss = ss, .out = in, .fail = "" }}; }}
    SR r = sstep(ss, in, 0, ListBuf(), []);
    if (str_len(r.fail) > 0) {{ return r; }}
    return srun(r.ss, r.out, rounds - 1);
}}

Str signed(List(SgP) ss, Int i) {{
    if (i >= ss.len()) {{ return ""; }}
    ThState st = ss[i].st;
    return match st {{ ThSigned(sig) => hex_encode(th_sig_raw(sig)), _ => signed(ss, i + 1) }};
}}


// ─── Re-share: dealers 1 and 3, receivers 1, 3, 4, offline 2 ────

type RsP = {{ Int id; RsState st; }};

Bool rfor(ThMsg m, Int me) {{
    return match m {{ ThRs(r) => r.from != me && (r.to == 0 || r.to == me), _ => false }};
}}

List(ThMsg) rinbox(List(ThMsg) all, Int me, Int i, ListBuf(ThMsg) acc) {{
    if (i >= all.len()) {{ return acc.finish(); }}
    Option(ThMsg) d = msg_decode(msg_encode(all[i]));
    ListBuf(ThMsg) a = match d {{ Some(m) => if (rfor(m, me)) {{ acc.push(m) }} else {{ acc }}, None => acc }};
    return rinbox(all, me, i + 1, a);
}}

type RR = {{ List(RsP) ps; List(ThMsg) out; Str fail; }};

RR rfailed(ListBuf(RsP) acc, CgFail e) {{ _ = acc.finish(); return RR {{ .ps = [], .out = [], .fail = e.why + f" {{e.culprits}}" }}; }}

RR rstep(List(RsP) ps, List(ThMsg) in, Int i, ListBuf(RsP) acc, List(ThMsg) out) {{
    if (i >= ps.len()) {{ return RR {{ .ps = acc.finish(), .out = out, .fail = "" }}; }}
    // A dealer that is not a receiver is addressed by its old id 0 in messages; it reads broadcasts.
    return match rs_step(ps[i].st, rinbox(in, ps[i].id, 0, ListBuf())) {{
        Err(e) => rfailed(acc, e),
        Ok(s) => rstep(ps, in, i + 1, acc.push(RsP {{ .id = ps[i].id, .st = s.state }}), out.concat(s.out))
    }};
}}

RR rrun(List(RsP) ps, List(ThMsg) in, Int rounds) {{
    if (rounds == 0) {{ return RR {{ .ps = ps, .out = in, .fail = "" }}; }}
    RR r = rstep(ps, in, 0, ListBuf(), []);
    if (str_len(r.fail) > 0) {{ return r; }}
    return rrun(r.ps, r.out, rounds - 1);
}}

RsCtx rctx(Int self, Int old_self, List(CgConfig) old, List(Int) root, Int pidx) {{
    return RsCtx {{ .self = self, .old_self = old_self, .dealers = [1, 3], .receivers = [1, 3, 4], .offline = [2], .degree = 1, .old = old,
                    .root = root, .session_id = bytes_of("symbolon reshare test"), .seed = sha256_bytes([self, old_self, 5]), .primes = primes()[pidx] }};
}}

RsResult none_res() {{ return RsResult {{ .cfg = None, .offline = [], .transcript = [] }}; }}

test "re-share to a new device: same key, kit share by the dealers, transcripts agree, the new set signs" {{
    List(CgConfig) cs = keygen();
    List(Int) x = cfg_root_pubkey(cs[0], [1, 2, 3]);
    RsStep a = rs_start(rctx(1, 1, [cs[0]], x, 3)) else {{ RsStep {{ .state = RSDone(none_res()), .out = [] }} }};
    RsStep b = rs_start(rctx(3, 3, [cs[2]], x, 4)) else {{ a }};
    RsStep n = rs_start(rctx(4, 0, [], x, 5)) else {{ a }};
    RR r = rrun([RsP {{ .id = 1, .st = a.state }}, RsP {{ .id = 3, .st = b.state }}, RsP {{ .id = 4, .st = n.state }}], a.out.concat(b.out).concat(n.out), 2);
    expect(r.fail).toEqual("");
    RsResult r1 = rs_result(r.ps[0].st) else {{ none_res() }};
    RsResult r3 = rs_result(r.ps[1].st) else {{ none_res() }};
    RsResult r4 = rs_result(r.ps[2].st) else {{ none_res() }};
    expect(hex_encode(r1.transcript)).toEqual(hex_encode(r4.transcript));
    expect(hex_encode(r3.transcript)).toEqual(hex_encode(r4.transcript));
    CgConfig n1 = r1.cfg else {{ none_cfg() }};
    CgConfig n3 = r3.cfg else {{ none_cfg() }};
    CgConfig n4 = r4.cfg else {{ none_cfg() }};
    expect(hex_encode(cfg_root_pubkey(n4, [1, 3, 4]))).toEqual(hex_encode(x));
    List(CgConfig) ncs = [n1, none_cfg(), n3, n4];
    expect(hex_encode(from_pair(ncs, 1, 4))).toEqual(hex_encode(x));
    expect(hex_encode(from_pair(ncs, 3, 4))).toEqual(hex_encode(x));
    expect(hex_encode(from_pair(ncs, 1, 3))).toEqual(hex_encode(x));
    // The kit's share: the dealers' offline contributions added.
    List(UInt(64)) xk = sc_nat_add(r1.offline[0].share, r3.offline[0].share);
    List(UInt(64)) viakit = sc_nat_add(sc_nat_mul(cg_lagrange([2, 4], 2), xk), sc_nat_mul(cg_lagrange([2, 4], 4), n4.ecdsa));
    expect(hex_encode(sec1_uncompressed(cv_mul_base(viakit)))).toEqual(hex_encode(x));
    // The old shares no longer combine with a new one.
    List(UInt(64)) mixed = sc_nat_add(sc_nat_mul(cg_lagrange([1, 4], 1), cs[0].ecdsa), sc_nat_mul(cg_lagrange([1, 4], 4), n4.ecdsa));
    expect(hex_encode(sec1_uncompressed(cv_mul_base(mixed))) == hex_encode(x)).toBeFalse();
    // The new device (4) and the cosigner (3) sign, 4 designated.
    Quorum q = Quorum {{ .parties = [party_of(1, party_kind_device()), party_of(2, party_kind_kit()), party_of(3, party_kind_cosigner()), party_of(4, party_kind_device())],
                         .t = 2, .root_pubkey = x, .epoch = 2, .transcript_digest = r4.transcript }};
    List(UInt(64)) tau = sc_of_bytes(sha256_bytes([8, 8]));
    List(Int) digest = sha256_bytes([4, 3, 2, 1]);
    List(List(Int)) signers = [[4, 4, 4, 4], [3, 3, 3, 3]];
    CgCtx c4 = th_ctx(n4, q, signers, [4, 4, 4, 4], tau, [6], digest, [21]) else {{ CgCtx {{ .self = 0, .ids = [], .pubs = [], .x = [], .elg = [], .psec = PaillierSec {{ .p = [], .q = [], .phi = [], .phi_inv = [] }}, .pubkey = cv_inf(), .base = tr_new(), .seed = [], .digest = [] }} }};
    CgCtx c3 = th_ctx(n3, q, signers, [4, 4, 4, 4], [], [6], digest, [23]) else {{ c4 }};
    ThStep s4 = th_start(c4, th_role(c4, q, [4, 4, 4, 4], tau));
    ThStep s3 = th_start(c3, th_role(c3, q, [4, 4, 4, 4], []));
    SR sr = srun([SgP {{ .ctx = c4, .st = s4.state }}, SgP {{ .ctx = c3, .st = s3.state }}], s4.out.concat(s3.out), 6);
    expect(sr.fail).toEqual("");
    List(Int) sig = cose_hex_decode(signed(sr.ss, 0));
    expect(ecdsa_verify_digest(P256, credential_pubkey(x, tau), digest, ecdsa_sig_raw(P256, sig))).toBeTrue();
}}
'''
open(os.path.join(HERE, '..', 'src', 'threshold', 'reshare_test.resid'), 'w').write(out)
